// tools/assemble-game-data.mjs — one-time pipeline (Project-100 build):
// merges the 8 per-module JSON files produced by the content agents into
// js/practice-data.js (88 challenges: 72 legacy ids + 16 new goodbad) and
// js/quiz-data.js (40 questions), every item carrying a verified sourceQuote.
//
// Usage: node tools/assemble-game-data.mjs --src <dir-with-module-N.json>
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.dirname(path.dirname(url.fileURLToPath(import.meta.url)));
const SRC = process.argv[process.argv.indexOf('--src') + 1];
if (!SRC || !fs.existsSync(SRC)) throw new Error('pass --src <dir>');

// ---- load helpers ----
const sandbox = {};
new Function('window', fs.readFileSync(path.join(ROOT, 'js', 'course-data.js'), 'utf8'))(sandbox);
const MODULES = sandbox.MODULES;

const kbIndex = JSON.parse(fs.readFileSync(path.join(ROOT, 'api', '_kb', '_index.json'), 'utf8'));
const validKeys = new Set(kbIndex.map(e => e.key));

// old quiz meta (title/icon/intro per module) is preserved
const quizSrc = fs.readFileSync(path.join(ROOT, 'js', 'quiz-data.js'), 'utf8');
const OLD_QUIZZES = new Function(quizSrc + '\n;return QUIZZES;')();

// Agents derived lesson keys from "שבוע X · יום Y" headers as m{mi}-{X-1}-{Y-1}.
// Module 1 has an intro week (weeks[0] = opening video), so its real key for
// week X is m0-{X}-{d}. Fix any key that isn't in the KB manifest.
function fixLessonKey(key, moduleIdx) {
  if (!key) return key;
  if (validKeys.has(key)) return key;
  const m = /^m(\d+)-(\d+)-(\d+)$/.exec(key);
  if (m && Number(m[1]) === moduleIdx) {
    const shifted = `m${m[1]}-${Number(m[2]) + 1}-${m[3]}`;
    if (validKeys.has(shifted)) return shifted;
  }
  console.warn(`  WARN unknown lessonKey ${key} (module ${moduleIdx}) — kept as is`);
  return key;
}

const allPractice = [];
const allQuiz = [];

for (let n = 1; n <= 8; n++) {
  const p = path.join(SRC, `module-${n}.json`);
  const d = JSON.parse(fs.readFileSync(p, 'utf8'));
  if (d.moduleIdx !== n - 1) throw new Error(`module-${n}.json moduleIdx mismatch`);
  for (const c of d.practice) {
    c.sourceLessonKey = fixLessonKey(c.sourceLessonKey, d.moduleIdx);
    allPractice.push(c);
  }
  for (const q of d.quiz) {
    if (q.src) q.src.lessonKey = fixLessonKey(q.src.lessonKey, d.moduleIdx);
  }
  allQuiz.push({ moduleIdx: d.moduleIdx, questions: d.quiz });
}

// ---- integrity checks ----
const ids = allPractice.map(c => c.id);
if (new Set(ids).size !== ids.length) throw new Error('duplicate challenge ids');
const legacy = ids.filter(id => !id.includes('goodbad'));
if (legacy.length !== 72) throw new Error(`legacy id count ${legacy.length} != 72`);
if (ids.length !== 88) throw new Error(`total challenges ${ids.length} != 88`);
for (const c of allPractice) {
  if (!c.sourceQuote) throw new Error(`${c.id} missing sourceQuote`);
  if (c.type === 'cloze' && !c.options.includes(c.correct)) throw new Error(`${c.id} correct not in options`);
}
const totalQuiz = allQuiz.reduce((a, m) => a + m.questions.length, 0);
if (totalQuiz !== 40) throw new Error(`quiz questions ${totalQuiz} != 40`);

// ---- serialize practice-data.js ----
const header = `// ===== Practice Challenges Data — עסק ללא מתחרים =====
// REGENERATED 2026-08-02 from the real course transcripts (Project-100 build,
// "questions from the real content"). Every challenge carries:
//   sourceQuote     — verbatim quote from the lesson transcript (verified
//                     programmatically against the KB before assembly)
//   sourceLessonKey — the lesson it comes from (deep-linkable)
// 88 challenges: the original 72 ids (rewritten content, ids preserved so
// existing learner progress survives) + 16 new 'goodbad' judgment challenges
// (2 per module — the fifth building block: good example vs bad example).
// Generated by tools/assemble-game-data.mjs — do not hand-edit ids.
// Schema consumed by js/practice.js. See pages/practice.html.

window.PRACTICE_CHALLENGES = `;

fs.writeFileSync(
  path.join(ROOT, 'js', 'practice-data.js'),
  header + JSON.stringify(allPractice, null, 2) + ';\n',
  'utf8'
);

// ---- serialize quiz-data.js (preserve module meta) ----
const quizOut = OLD_QUIZZES.map((old, mi) => ({
  moduleIndex: mi,
  title: old.title,
  icon: old.icon,
  intro: old.intro,
  questions: allQuiz.find(m => m.moduleIdx === mi).questions,
}));

const quizHeader = `// ===== Quiz Data - עסק ללא מתחרים =====
// REGENERATED 2026-08-02 from the real course transcripts (Project-100 build).
// Each question: q, a (4 options), c (correct index), e (explanation),
// src { quote, lessonKey } — verbatim transcript quote shown after answering.
// Generated by tools/assemble-game-data.mjs.

const QUIZZES = `;

fs.writeFileSync(
  path.join(ROOT, 'js', 'quiz-data.js'),
  quizHeader + JSON.stringify(quizOut, null, 2) + ';\n',
  'utf8'
);

console.log(`practice: ${allPractice.length} challenges (${legacy.length} legacy + ${ids.length - legacy.length} goodbad)`);
console.log(`quiz: ${totalQuiz} questions across ${quizOut.length} modules`);
console.log('written: js/practice-data.js, js/quiz-data.js');
