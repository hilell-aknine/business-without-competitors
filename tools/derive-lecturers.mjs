// derive-lecturers.mjs — who actually speaks in each lesson (2026-10-22).
//
// WHY: the AI coach kept saying "כמו שרם אמר" in every lesson. Measured on
// the transcripts: the name "רם" appears 0 times in all 8 modules. The opening
// video says it outright: "אני צביקה ... זו בת זוגתי ... תמר ... הצטרפנו ביחד
// לעשות את תוכנית ההכשרה". Ram is mentioned only inside seminars, by Tzvika,
// as a third person. The old system prompt ("הקורס של רם, צביקה ותמר") plus a
// placeholder that read "איזו דוגמה רם נתן?" made the model pick Ram.
//
// HOW (evidence only, nothing guessed):
//   1. Tamar: the 19 Tuesday lessons of TRACKS['tamar-tuesday'] in
//      js/course-data.js, verified against the transcripts on 2026-08-16.
//   2. Gender of first-person speech: "אני חושב/יודע/מרגיש..." (male) vs
//      "אני חושבת/יודעת/מרגישה..." (female). The program has exactly two
//      lecturers, Tzvika and Tamar (opening video), so a clearly male-voiced
//      lesson is Tzvika's.
//   3. Too little signal, or both voices present, is recorded as such, and
//      the coach is told not to put a name on it.
//
// Input:  api/_kb/<key>.json plaintext (local dev only, gitignored).
// Output: api/_lib/lecturers.js  (names + evidence counts, no transcript text)
// Run:    node tools/derive-lecturers.mjs

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import vm from 'node:vm';

const ROOT = path.dirname(path.dirname(url.fileURLToPath(import.meta.url)));
const KB = path.join(ROOT, 'api', '_kb');
const OUT = path.join(ROOT, 'api', '_lib', 'lecturers.js');

// TRACKS from the browser data file, without a DOM.
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'js', 'course-data.js'), 'utf8') + '\nthis.__T = TRACKS;', ctx);
const TAMAR = new Set(ctx.__T.find(t => t.id === 'tamar-tuesday').lessons.map(l => l.key));

// Lessons whose transcript is one of two recorded versions (KB holds one).
const TWO_VERSIONS = new Set(['m3-1-2']);
// Documented in course-data.js: labelled "(צביקה)" in the source course, or
// verified Tzvika-solo when the Tamar track was built.
const DOCUMENTED_TZVIKA = new Set(['m3-2-2', 'm4-1-2', 'm6-1-2']);

const VERBS = {
  'חושב': 'חושבת', 'יודע': 'יודעת', 'מרגיש': 'מרגישה', 'אומר': 'אומרת',
  'מבקש': 'מבקשת', 'מזמין': 'מזמינה', 'ממליץ': 'ממליצה', 'מאמין': 'מאמינה',
  'אוהב': 'אוהבת', 'צריך': 'צריכה', 'יכול': 'יכולה', 'הולך': 'הולכת',
  'מדבר': 'מדברת', 'מסביר': 'מסבירה',
};
const count = (t, w) => (t.match(new RegExp('אני ' + w + '(?![א-ת])', 'g')) || []).length;

const index = JSON.parse(fs.readFileSync(path.join(KB, '_index.json'), 'utf8'));
const out = {};
const tally = { 'צביקה': 0, 'תמר': 0, mixed: 0, unknown: 0 };

for (const { key } of index) {
  const file = path.join(KB, key + '.json');
  if (!fs.existsSync(file)) continue;
  const text = JSON.parse(fs.readFileSync(file, 'utf8')).text.replace(/\s+/g, ' ');
  const male = Object.keys(VERBS).reduce((s, v) => s + count(text, v), 0);
  const female = Object.values(VERBS).reduce((s, v) => s + count(text, v), 0);
  const selfTz = /אני צביקה/.test(text);
  const selfTamar = /אני תמר/.test(text);

  let rec;
  if (TWO_VERSIONS.has(key)) {
    rec = { lecturer: null, note: 'two_versions', why: 'two recorded versions (Tzvika / Tamar), KB holds one' };
  } else if (TAMAR.has(key)) {
    rec = male >= 3
      ? { lecturer: 'תמר', with: selfTz ? 'צביקה' : 'other', why: `Tamar track; male voice also present (m${male}/f${female})` }
      : { lecturer: 'תמר', why: `Tamar track (m${male}/f${female})` };
  } else if (selfTz && selfTamar) {
    rec = { lecturer: 'צביקה', with: 'תמר', why: 'both introduce themselves' };
  } else if (DOCUMENTED_TZVIKA.has(key) && female <= 1) {
    rec = { lecturer: 'צביקה', why: `documented Tzvika lesson (m${male}/f${female})` };
  } else if (male >= 5 && female <= Math.max(2, Math.floor(male * 0.15))) {
    rec = { lecturer: 'צביקה', why: `male first-person voice (m${male}/f${female})` };
  } else if (male >= 5 && female >= 4) {
    rec = { lecturer: 'צביקה', with: selfTamar ? 'תמר' : 'other', why: `male voice leads, female voice also present (m${male}/f${female})` };
  } else {
    rec = { lecturer: null, why: `not enough signal (m${male}/f${female})` };
  }
  out[key] = rec;
  if (!rec.lecturer) tally.unknown++;
  else if (rec.with) tally.mixed++;
  else tally[rec.lecturer]++;
}

const body = `// GENERATED by tools/derive-lecturers.mjs — do not edit by hand.
// Who speaks in each lesson, derived from the transcripts (see the tool for
// the method). lecturer=null means "not known for sure": the coach must not
// put a name on it. \`with\` = a second voice also heard in the lesson: a
// name only when that person introduces themselves in it, else 'other'
// (a participant or a second lecturer, not known which).
// Ram (רם) is not a lecturer in any lesson: 0 mentions in all 8 modules.
// Tally: ${JSON.stringify(tally)}

export const LECTURERS = ${JSON.stringify(out, null, 2)};

export function lecturerOf(lessonKey) {
  return LECTURERS[lessonKey] || { lecturer: null, why: 'no transcript' };
}
`;
fs.writeFileSync(OUT, body);
console.log('wrote', path.relative(ROOT, OUT), tally);
