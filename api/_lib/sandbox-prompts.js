// Prompts for the atomic sandbox (api/sandbox.js). Added 2026-11-16, pilot on
// module 2 (moduleIdx 1). Five exercises, in this order on purpose:
//   1 teach me      retrieval practice: explain to a curious beginner, lesson locked
//   2 the mirror    personal value: how the concept looks in MY business tomorrow
//   3 the skeptic   goal-based scenario: a customer from my niche, then a mentor debrief
//   4 pre-mortem    prospective hindsight on the plan from exercise 2
//   5 if-then       one implementation intention, saved and followed up next visit
//
// Iron rules shared by all five (see rules() below):
//   - the AI never writes the learner's answer, not even when asked to
//     (Bastani et al., PNAS 2025: guard-railed tutors kept the learning gains)
//   - everything about the material comes from the attached transcript passages
//   - feedback quotes the lesson, and a quote may ONLY come from the verified
//     list (game src.quote lines). The server checks every «...» against that
//     list and credits the lesson it came from: attribution is proven, not
//     self-reported (a self-reported [[source]] tag over-attributes, see
//     hindsight 2026-08-10).
//
// Plain text out, no JSON. Markers the server reads:
//   «...»                a lesson quote (verified server side)
//   [[סוף-תרגיל]]        the exercise reached its goal
//   [[תוכנית-מאושרת]]    exercise 5 only: the learner's last sentence is the plan

export const QUOTE_RE = /«([^«»\n]{3,400})»/g;
export const MARK_SOURCE = /\[\[\s*מקור\s*:([^\]]*)\]\]/g; // stripped if a model writes one anyway
export const MARK_DONE = /\[\[\s*סוף[-\s]?תרגיל\s*\]\]/;
export const MARK_PLAN = /\[\[\s*תוכנית[-\s]?מאושרת\s*\]\]/;
// A reply cut by max_tokens can end in the middle of a marker.
export const MARK_DANGLING = /\[\[[^\]]*$/;

// Learner turns per exercise. At the limit the server tells the model to close.
export const TURN_LIMITS = {
  1: { light: 5, hard: 6 },
  2: { light: 4, hard: 5 },
  3: { light: 6, hard: 8 }, // the debrief comes after 6 to 8 learner messages
  4: { light: 5, hard: 6 },
  5: { light: 5, hard: 6 },
};

function g(profile, fem, masc) {
  return profile && profile.gender === 'f' ? fem : masc;
}

function speakerNote(lecturers) {
  const names = [...new Set(lecturers.filter(Boolean))];
  const who = names.length ? `המרצים בשיעורים המצורפים: ${names.join(' ו')}.` : '';
  return `${who} כשאתה מייחס משהו למרצה, השתמש רק בשם שמופיע ליד השיעור. אם אין שם, כתוב "בשיעור". אל תייחס אף פעם דברים לרם: הוא לא מרצה באף שיעור.`;
}

function genderRule(profile) {
  return profile && profile.gender === 'f'
    ? '6. הלומדת היא אישה. כל פנייה אליה בלשון נקבה, בכל משפט: "את", "שלך", "כתבי", "תבחרי", "את יושבת", "את רוצה", "היית יכולה". אסור "אתה", "תכתוב", "אתה יושבת". בדוק כל פועל שפונה אליה לפני שאתה כותב אותו.'
    : '6. פנה ללומד בלשון זכר: "אתה", "כתוב", "תבחר".';
}

