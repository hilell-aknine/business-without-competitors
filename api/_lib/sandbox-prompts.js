function profileBlock(profile) {
  if (!profile) return 'אין לנו פרטים על העסק של הלומד.';
  const lines = ['העסק של הלומד (מה שהוא עצמו כתב; השאלות צריכות להיות על העסק הזה):'];
  if (profile.sells) lines.push(`- מה מוכר: ${profile.sells}`);
  if (profile.audience) lines.push(`- למי: ${profile.audience}`);
  if (profile.edge) lines.push(`- מה מבדל: ${profile.edge}`);
  if (profile.doc) lines.push('- מסמך היישום שכתב בעוזר היישום:', profile.doc);
  return lines.join('\n');
}

function weakBlock(weak) {
  if (!weak || !weak.length) return '';
  return [
    'מה הלומד פספס במשחק התרגול של המודול (התחל מהמקומות האלה כשזה רלוונטי):',
    ...weak.map(w => `- ${w}`),
  ].join('\n');
}

function passagesBlock(passages) {
  const out = ['--- קטעים מתמלולי השיעורים (המקור היחיד לחומר) ---'];
  for (const p of passages) {
    out.push(`### שיעור: ${p.title}${p.lecturer ? ` (מרצה: ${p.lecturer})` : ' (מרצה: לא לציין שם)'}`, p.text);
    if (p.quotes && p.quotes.length) {
      out.push('ציטוטים מאומתים מהשיעור הזה (רק אותם מותר לשים בתוך «»):', ...p.quotes.map(q => `- «${q}»`));
    }
    out.push('');
  }
  out.push('--- סוף הקטעים ---');
  return out.join('\n');
}

